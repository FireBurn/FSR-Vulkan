"""Generate the embedded, project-authored Vulkan unit-conversion shaders."""
import hashlib
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile

root=Path(__file__).resolve().parents[1]
source=root/'shaders/xess/xess_input_conversion.comp'
output=root/'src/xess_input_conversion_spv.h'
glslang=shutil.which('glslangValidator')
validator=shutil.which('spirv-val')
if not glslang or not validator:
    raise SystemExit('glslangValidator and spirv-val are required')
lines=['// SPDX-License-Identifier: MIT','// Generated by tools/generate_xess_input_conversion.py',
    '// Source SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),
    '#pragma once','#include <cstdint>','namespace ffxvk {']
with tempfile.TemporaryDirectory() as temporary:
    for name,flags in [('xess_input_conversion_spv',[]),('xess_output_conversion_spv',['-DOUTPUT_ONLY=1'])]:
        binary=Path(temporary)/(name+'.spv')
        subprocess.run([glslang,'-V','--target-env','vulkan1.3','-Os',*flags,'-o',str(binary),str(source)],check=True)
        subprocess.run([validator,'--target-env','vulkan1.3',str(binary)],check=True)
        data=binary.read_bytes();words=struct.unpack('<'+'I'*(len(data)//4),data)
        lines.append('inline constexpr uint32_t '+name+'[] = {')
        lines.extend('    '+','.join(f'0x{word:08x}u' for word in words[i:i+8])+',' for i in range(0,len(words),8))
        lines.append('};')
lines.append('} // namespace ffxvk')
output.write_text('\n'.join(lines)+'\n')
